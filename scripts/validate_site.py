#!/usr/bin/env python3
"""Offline deployment checks; standard library only. Run after the full render."""
import argparse
import hashlib
from html.parser import HTMLParser
import json
import os
from pathlib import Path
from urllib.parse import unquote, urlsplit


class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.lang = None
        self.title = []
        self.in_title = False
        self.ids = set()
        self.references = []
        self.viewport = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "html":
            self.lang = attrs.get("lang")
        if tag == "title":
            self.in_title = True
        if tag == "meta" and attrs.get("name") == "viewport":
            self.viewport = bool(attrs.get("content"))
        if attrs.get("id"):
            self.ids.add(attrs["id"])
        if tag == "a" and attrs.get("name"):
            self.ids.add(attrs["name"])
        for attr in ("href", "src"):
            if attrs.get(attr):
                self.references.append(attrs[attr])

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False

    def handle_data(self, data):
        if self.in_title:
            self.title.append(data)


def check_pages(output):
    output = Path(output).resolve()
    errors = []
    pages = {}
    for path in sorted(output.rglob("*.html")):
        page = Page()
        try:
            page.feed(path.read_text(encoding="utf-8"))
        except (UnicodeError, OSError) as exc:
            errors.append(f"Cannot read {path.relative_to(output)}: {exc}")
            continue
        pages[path] = page
        relative = path.relative_to(output)
        # Teaching (the course catalogue and course materials) is in Portuguese;
        # the rest of the site is in English.
        pt_br = relative.parts[0] == "teaching" or relative.as_posix() == "teaching.html"
        expected = "pt-BR" if pt_br else "en"
        if page.lang != expected:
            errors.append(f"{relative}: expected lang={expected}, got {page.lang!r}")
        if not "".join(page.title).strip():
            errors.append(f"{relative}: missing page title")
        if not page.viewport:
            errors.append(f"{relative}: missing viewport metadata")
    if not pages:
        errors.append("No HTML pages were generated")
    for path, page in pages.items():
        for reference in page.references:
            url = urlsplit(reference)
            if url.scheme or url.netloc:
                continue
            local = unquote(url.path)
            target = (output / local.lstrip("/") if local.startswith("/")
                      else path.parent / local) if local else path
            target = target.resolve()
            if not target.is_relative_to(output):
                errors.append(f"{path.relative_to(output)}: target escapes output directory: {reference}")
                continue
            if target.is_dir():
                target /= "index.html"
            if not target.is_file():
                errors.append(f"{path.relative_to(output)}: missing target {reference}")
            elif url.fragment and target in pages and unquote(url.fragment) not in pages[target].ids:
                errors.append(f"{path.relative_to(output)}: missing anchor {reference}")
    return errors


def md5(path):
    return hashlib.md5(Path(path).read_bytes()).hexdigest()


def check_cv_build(source, output, manifest, build_id):
    errors = []
    try:
        record = json.loads(Path(manifest).read_text())
        if record.get("build_id") != build_id:
            errors.append("CV PDF was not generated by this build")
        pdf = Path(output) / "assets/cv.pdf"
        content = pdf.read_bytes()
        if not content.startswith(b"%PDF-") or b"%%EOF" not in content[-1024:]:
            errors.append("CV output is not a complete PDF")
        if record.get("pdf_md5") != md5(pdf):
            errors.append("Published CV PDF differs from the PDF generated by this build")
        required = {"cv.qmd", "data/publications.yml", "R/pubs.R", "R/metrics.R",
                    "assets/metrics.yml", "assets/styles/cv.css", "styles.css",
                    "_quarto.yml", "scripts/build_cv_pdf.R"}
        hashes = record.get("source_hashes", {})
        if not isinstance(hashes, dict) or set(hashes) != required:
            errors.append("CV build manifest has an incomplete source list")
        else:
            for relative, expected in hashes.items():
                if md5(Path(source) / relative) != expected:
                    errors.append(f"CV PDF is out of date for {relative}")
    except (OSError, ValueError, TypeError, AttributeError) as exc:
        errors.append(f"Cannot verify CV build: {exc}")
    return errors


def validate_site(source, output, manifest, build_id):
    source, output = Path(source).resolve(), Path(output).resolve()
    errors = check_pages(output)
    required = {"index.html", "cv.html", "publications.html", "teaching.html",
                "news/index.html", "assets/cv.pdf", "assets/favicon.png",
                "assets/navbar-logo.png", "CNAME", "search.json", "sitemap.xml"}
    inputs = list(source.glob("*.qmd"))
    for directory in ("news", "teaching"):
        inputs.extend((source / directory).rglob("*.qmd"))
    required.update(str(path.relative_to(source).with_suffix(".html")) for path in inputs)
    for relative in sorted(required):
        target = output / relative
        if not target.is_file() or not target.stat().st_size:
            errors.append(f"Missing or empty required output: {relative}")
    if (output / "CNAME").is_file() and (output / "CNAME").read_text().strip() != "provetelab.org":
        errors.append("CNAME does not match provetelab.org")
    errors.extend(check_cv_build(source, output, manifest, build_id))
    return sorted(set(errors))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("."))
    parser.add_argument("--output", type=Path, default=Path("docs"))
    parser.add_argument("--manifest", type=Path, default=Path(".quarto/cv-build.json"))
    parser.add_argument("--build-id", default=os.environ.get("SITE_BUILD_ID", "local"))
    args = parser.parse_args()
    errors = validate_site(args.source, args.output, args.manifest, args.build_id)
    if errors:
        for error in errors:
            print(f"ERROR: {error}")
        raise SystemExit(1)
    print(f"Site validated: {len(list(args.output.rglob('*.html')))} HTML pages, local links, languages and current CV PDF.")


if __name__ == "__main__":
    main()
