import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location(
    "validate_site", Path(__file__).resolve().parents[1] / "scripts/validate_site.py")
validator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(validator)


def html(lang="en", body=""):
    return (f'<html lang="{lang}"><head><title>Example</title>'
            '<meta name="viewport" content="width=device-width"></head>'
            f'<body>{body}</body></html>')


class SiteChecks(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.output = self.root / "docs"
        self.output.mkdir()
        (self.output / "index.html").write_text(html(body='<a href="teaching/course/#lesson">Course</a>'))
        course = self.output / "teaching/course/index.html"
        course.parent.mkdir(parents=True)
        course.write_text(html("pt-BR", '<h1 id="lesson">Aula</h1>'))
        self.course = course

    def test_valid_pages_and_course_language(self):
        self.assertEqual(validator.check_pages(self.output), [])

    def test_missing_download_blocks_deployment(self):
        (self.output / "index.html").write_text(html(body='<a href="slides/missing.pdf">Slides</a>'))
        self.assertTrue(any("missing target" in x for x in validator.check_pages(self.output)))

    def test_wrong_course_language_blocks_deployment(self):
        self.course.write_text(html("en", '<h1 id="lesson">Aula</h1>'))
        self.assertTrue(any("expected lang=pt-BR" in x for x in validator.check_pages(self.output)))

    def test_missing_anchor_blocks_deployment(self):
        self.course.write_text(html("pt-BR"))
        self.assertTrue(any("missing anchor" in x for x in validator.check_pages(self.output)))

    def test_missing_metadata_blocks_deployment(self):
        self.course.write_text('<html lang="pt-BR"><body>Lesson</body></html>')
        errors = validator.check_pages(self.output)
        self.assertTrue(any("missing page title" in x for x in errors))
        self.assertTrue(any("missing viewport" in x for x in errors))

    def make_cv_manifest(self):
        inputs = ["cv.qmd", "data/publications.yml", "R/pubs.R", "R/metrics.R",
                  "assets/metrics.yml", "assets/styles/cv.css", "styles.css",
                  "_quarto.yml", "scripts/build_cv_pdf.R"]
        for relative in inputs:
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("original source")
        pdf = self.output / "assets/cv.pdf"
        pdf.parent.mkdir()
        pdf.write_bytes(b"%PDF-1.7\n%%EOF\n")
        record = {"build_id": "current-run", "pdf_md5": validator.md5(pdf),
                  "source_hashes": {path: validator.md5(self.root / path) for path in inputs}}
        manifest = self.root / "cv-build.json"
        manifest.write_text(json.dumps(record))
        return manifest

    def test_current_pdf_passes(self):
        manifest = self.make_cv_manifest()
        self.assertEqual(validator.check_cv_build(self.root, self.output, manifest, "current-run"), [])

    def test_old_build_blocks_deployment(self):
        manifest = self.make_cv_manifest()
        errors = validator.check_cv_build(self.root, self.output, manifest, "next-run")
        self.assertTrue(any("not generated by this build" in x for x in errors))

    def test_changed_bibliography_invalidates_pdf(self):
        manifest = self.make_cv_manifest()
        (self.root / "data/publications.yml").write_text("new paper")
        errors = validator.check_cv_build(self.root, self.output, manifest, "current-run")
        self.assertTrue(any("out of date for data/publications.yml" in x for x in errors))

    def test_changed_or_truncated_pdf_blocks_deployment(self):
        manifest = self.make_cv_manifest()
        (self.output / "assets/cv.pdf").write_bytes(b"%PDF-truncated")
        errors = validator.check_cv_build(self.root, self.output, manifest, "current-run")
        self.assertTrue(any("not a complete PDF" in x for x in errors))
        self.assertTrue(any("differs from the PDF" in x for x in errors))


if __name__ == "__main__":
    unittest.main()
